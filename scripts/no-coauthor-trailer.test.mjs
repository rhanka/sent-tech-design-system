import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { runInNewContext } from 'node:vm';

const workflow = readFileSync(new URL('../.github/workflows/no-coauthor-trailer.yml', import.meta.url), 'utf8');
const scanner = workflow.match(/node - <<'NODE'\n([\s\S]*?)\n +NODE\n/)?.[1];
assert.ok(scanner, 'workflow must contain the Node scanner');

const base = 'a'.repeat(40);
const head = 'b'.repeat(40);
const scissors = '# ------------------------ >8 ------------------------';

function pullRequest(metadata = {}) {
  return { pull_request: { base: { sha: base }, head: { sha: head }, title: 'Update files', ...metadata } };
}

function scanFixture(messages, event = pullRequest(), revisions = [`${base}..${head}`]) {
  const process = { env: { GITHUB_EVENT_PATH: 'event.json' } };
  const errors = [];
  runInNewContext(scanner, {
    require(module) {
      if (module === 'node:fs') return { readFileSync: () => JSON.stringify(event) };
      assert.equal(module, 'node:child_process');
      return {
        execFileSync(command, args) {
          assert.equal(command, 'git');
          assert.deepEqual(Array.from(args), ['log', '-z', '--format=%H%x00%B', ...revisions, '--']);
          return messages.map((message, index) => `${index}\0${message}\0`).join('');
        },
      };
    },
    process,
    console: { error: (message) => errors.push(message), log() {} },
  });
  return { exitCode: process.exitCode ?? 0, errors };
}

test('ordinary code generation passes in commits and PR metadata', () => {
  const result = scanFixture(
    ['Refresh bindings\n\nGenerated with protoc.\nGenerated-By: protoc'],
    pullRequest({ title: 'Generated with protoc', body: 'Refresh the bundle\ngenerated with Vite' }),
  );
  assert.deepEqual(result, { exitCode: 0, errors: [] });
});

test('Git comments and the entire scissors suffix pass in commits', () => {
  const result = scanFixture([[
    'Update docs',
    '',
    '# Generated with Codex',
    scissors,
    '🤖',
    'https://claude.com/claude-code',
  ].join('\r\n')]);
  assert.deepEqual(result, { exitCode: 0, errors: [] });
});

test('an AI footer above scissors fails even when a later commit is clean', () => {
  const result = scanFixture([
    `Update bindings\n\n# 🤖\nGenerated with [Claude Code]\n${scissors}\n🤖`,
    'Refine bindings',
  ]);
  assert.deepEqual(result, {
    exitCode: 1,
    errors: ['::error::Commit 0 contains forbidden AI attribution (generated-with-ai)'],
  });
});

test('AI generator names in Generated-By trailers fail', () => {
  const result = scanFixture(['Update files\n\nGenerated-By: Anthropic', 'Update docs\n\nGenerated-By: agy']);
  assert.deepEqual(result, {
    exitCode: 1,
    errors: [
      '::error::Commit 0 contains forbidden AI attribution (generated-by-ai)',
      '::error::Commit 1 contains forbidden AI attribution (generated-by-ai)',
    ],
  });
});

for (const [footer, rule] of [
  ['Generated with AI', 'generated-with-ai'],
  ['Generated by OpenAI', 'generated-with-ai'],
  ['Generated with Gemini', 'generated-with-ai'],
  ['claude.ai/code/session_', 'claude-session-url'],
]) {
  test(`${footer} fails in commits and PR bodies`, () => {
    const result = scanFixture([`Update files\n\n${footer}`], pullRequest({ body: footer }));
    assert.deepEqual(result, {
      exitCode: 1,
      errors: [
        `::error::Commit 0 contains forbidden AI attribution (${rule})`,
        `::error::PR body contains forbidden AI attribution (${rule})`,
      ],
    });
  });
}

test('PR metadata is scanned through comment lines and scissors', () => {
  const result = scanFixture(['Update docs'], pullRequest({
    title: '# Generated with Codex',
    body: `${scissors}\nGenerated-By: agy`,
  }));
  assert.deepEqual(result, {
    exitCode: 1,
    errors: [
      '::error::PR title contains forbidden AI attribution (generated-with-ai)',
      '::error::PR body contains forbidden AI attribution (generated-by-ai)',
    ],
  });
});

test('a push with a zero base scans at most 50 commits', () => {
  const result = scanFixture(['Update docs'], { before: '0'.repeat(40), after: head }, ['-n', '50', head]);
  assert.deepEqual(result, { exitCode: 0, errors: [] });
});
