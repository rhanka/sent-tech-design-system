import fs from 'node:fs';
const source = fs.readFileSync(new URL('../packages/tokens/src/diagramSpacing.ts', import.meta.url), 'utf8');
const path = new URL('../packages/diagram-canvas/src/layout/spacing.generated.ts', import.meta.url);
const output = '// Generated by scripts/sync-diagram-spacing.mjs. Edit tokens/src/diagramSpacing.ts.\n' + source;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path, 'utf8') !== output) throw new Error('Run node scripts/sync-diagram-spacing.mjs');
} else fs.writeFileSync(path, output);
