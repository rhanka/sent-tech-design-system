// Third-party notices for the built page.
//
// gas/demo.html is a redistributed copy of every package the bundler inlines
// (minified, so their own licence comments are gone) and of the Inter font
// (base64). The copyright and permission notices therefore have to travel with
// the page. The inventory is MEASURED, not listed by hand: it is the set of
// packages that own a module with rendered code in the script chunk, plus the
// build-time inputs declared in build.ts (font, theme tokens). The licence
// texts are re-read from the installed packages, never retyped.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export interface EmbeddedPackage {
  /** Absolute path of the package root (the folder holding its package.json). */
  dir: string;
  /** How the package ends up in the page. */
  embeddedAs: string;
}

export const NOTICES_FILENAME = "THIRD-PARTY-NOTICES.md";

// Root-level licence carriers only (a nested LICENSE belongs to a sub-work).
// The separator class covers LICENSE.md, LICENSE-MIT, LICENSE.THIRD-PARTY.md.
const LICENSE_FILE_RE = /^(licen[sc]e|copying|notice)([._-].*)?$/i;

/** Package root of a module id inside node_modules, or null for local sources. */
export function packageDirOf(moduleId: string): string | null {
  const clean = moduleId.replace(/^\0+/, "").split("?")[0]!.replaceAll("\\", "/");
  const marker = "/node_modules/";
  const at = clean.lastIndexOf(marker);
  if (at < 0) return null;
  const parts = clean.slice(at + marker.length).split("/");
  const name = parts[0]!.startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0]!;
  return `${clean.slice(0, at + marker.length)}${name}`;
}

export function renderNotices(packages: EmbeddedPackage[]): string {
  const byDir = new Map<string, string[]>();
  for (const { dir, embeddedAs } of packages) byDir.set(dir, [...(byDir.get(dir) ?? []), embeddedAs]);

  const entries = [...byDir].map(([dir, uses]) => {
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { name?: string; version?: string; license?: string };
    if (!manifest.name || !manifest.version) throw new Error(`${dir}: package.json has no name/version`);
    if (typeof manifest.license !== "string" || manifest.license.trim() === "") throw new Error(`${manifest.name}: package.json declares no licence`);
    const files = readdirSync(dir).filter((file) => LICENSE_FILE_RE.test(file)).sort();
    if (files.length === 0) throw new Error(`${manifest.name}@${manifest.version}: no licence file at the package root — its notice cannot be reproduced`);
    return { name: manifest.name, version: manifest.version, license: manifest.license, uses: [...new Set(uses)].sort(), dir, files };
  }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  const out: string[] = [
    "# Third-party notices — apps-script-demo",
    "",
    "Generated by `scripts/build.ts`. Do not edit: `npm run build` rewrites this file and",
    "`npm run check` fails when it differs from a fresh build.",
    "",
    "`demo.html` is a single self-contained page. It embeds a copy of the packages listed",
    "below: script and style code bundled and minified by the build, and the Inter font as a",
    "base64 `data:` URI. Their copyright and licence notices are reproduced here in full, and",
    "the same text is embedded as a comment at the top of `demo.html`, so the notices travel",
    "with the page wherever it is copied.",
    "",
    "## Inventory",
    "",
    "| Package | Version | Licence | Embedded as |",
    "| --- | --- | --- | --- |",
    ...entries.map((entry) => `| \`${entry.name}\` | ${entry.version} | ${entry.license} | ${entry.uses.join("; ")} |`),
    "",
    "## Licence texts",
    "",
  ];
  for (const entry of entries) {
    out.push(`### ${entry.name} ${entry.version} — ${entry.license}`, "");
    for (const file of entry.files) {
      const text = readFileSync(join(entry.dir, file), "utf8").replace(/\r\n/g, "\n").replace(/\s+$/, "");
      out.push(`From \`${entry.name}/${file}\`:`, "", ...text.split("\n").map((line) => (line === "" ? "" : `    ${line}`)), "");
    }
  }
  return `${out.join("\n").replace(/\s+$/, "")}\n`;
}

const COMMENT_PREAMBLE =
  "THIRD-PARTY NOTICES. This page embeds third-party software and a font; their copyright and\n" +
  "licence notices follow. Same text as THIRD-PARTY-NOTICES.md, except that HTML comment\n" +
  "delimiters occurring inside the reproduced files are written with a space (\"<!- -\", \"- ->\")\n" +
  "so that they cannot end this comment.\n\n";

/**
 * The comment block that carries the notices at the top of the page. Some
 * upstream notice files are Markdown with HTML comments of their own; their
 * delimiters are spaced out (and only those), which the preamble states.
 */
export function noticesComment(notices: string): string {
  const body = notices.replaceAll("<!--", "<!- -").replaceAll("-->", "- ->").replaceAll("--!>", "- -!>");
  for (const forbidden of ["-->", "--!>", "<!--"]) {
    if (body.includes(forbidden)) throw new Error(`The notices still contain ${JSON.stringify(forbidden)} after escaping`);
  }
  return `<!--\n${COMMENT_PREAMBLE}${body}-->\n`;
}

export const packageRootFromEntry = (resolvedFile: string): string => {
  let dir = resolvedFile.replaceAll("\\", "/");
  while (dir.includes("/")) {
    dir = dir.slice(0, dir.lastIndexOf("/"));
    if (existsSync(join(dir, "package.json")) && /\/node_modules\/(@[^/]+\/)?[^/]+$/.test(dir)) return dir;
  }
  throw new Error(`No package root found for ${resolvedFile}`);
};
