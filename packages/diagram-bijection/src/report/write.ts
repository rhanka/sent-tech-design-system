// Writing and guarding generated reports (§2.3): a report is a pair
// `<id>.report.json` (canonical bytes + LF) and `<id>.report.md` (rendered
// from the JSON, stamp included). DL-0 commits no report; these helpers serve
// CI artefact directories and local output directories.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalBytes, sha256Hex } from "@sentropic/diagram-core";
import { renderReportMarkdown, REPORT_MD_STAMP } from "./markdown.js";
import type { BijectionReport } from "./schema.js";

export interface WrittenReport {
  readonly jsonPath: string;
  readonly mdPath: string;
  readonly jsonSha256: string;
}

/** Write the report pair into `dir`. Returns the paths and the JSON digest. */
export function writeReport(dir: string, report: BijectionReport): WrittenReport {
  const jsonPath = join(dir, `${report.fixture.id}.report.json`);
  const jsonBytes = `${canonicalBytes(report)}\n`;
  writeFileSync(jsonPath, jsonBytes);
  const jsonSha256 = sha256Hex(jsonBytes);
  const mdPath = join(dir, `${report.fixture.id}.report.md`);
  writeFileSync(mdPath, renderReportMarkdown(report, jsonPath, jsonSha256));
  return { jsonPath, mdPath, jsonSha256 };
}

export type ReportGuardFailure =
  | { readonly code: "report-md-orphan"; readonly mdPath: string }
  | { readonly code: "report-md-hand-edited"; readonly mdPath: string; readonly detail: string };

/**
 * Check every `*.report.md` of `dir`: the sibling JSON must exist, the stamp
 * digest must equal the JSON sha256, and the body must equal a fresh render.
 */
export function checkGeneratedReports(dir: string): { readonly ok: true } | { readonly ok: false; readonly failures: readonly ReportGuardFailure[] } {
  const failures: ReportGuardFailure[] = [];
  if (!existsSync(dir)) return { ok: true };
  for (const name of readdirSync(dir).filter((n) => n.endsWith(".report.md")).sort()) {
    const mdPath = join(dir, name);
    const jsonPath = join(dir, name.replace(/\.report\.md$/, ".report.json"));
    if (!existsSync(jsonPath)) {
      failures.push({ code: "report-md-orphan", mdPath });
      continue;
    }
    const jsonBytes = readFileSync(jsonPath, "utf8");
    const jsonSha256 = sha256Hex(jsonBytes);
    const md = readFileSync(mdPath, "utf8");
    const stamp = `<!-- generated by @sentropic/diagram-bijection ${REPORT_MD_STAMP} from ${jsonPath} sha256 ${jsonSha256}; do not edit -->`;
    const firstLine = md.split("\n", 1)[0] ?? "";
    if (firstLine !== stamp) {
      failures.push({ code: "report-md-hand-edited", mdPath, detail: "stamp differs" });
      continue;
    }
    const report = JSON.parse(jsonBytes) as BijectionReport;
    const rendered = renderReportMarkdown(report, jsonPath, jsonSha256);
    if (md !== rendered) {
      failures.push({ code: "report-md-hand-edited", mdPath, detail: "body differs from renderReportMarkdown" });
    }
  }
  return failures.length === 0 ? { ok: true } : { ok: false, failures };
}
