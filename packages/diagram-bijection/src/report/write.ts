// Writing and guarding generated reports (§2.3): a report is a pair
// `<id>.report.json` (canonical bytes + LF) and `<id>.report.md` (rendered
// from the JSON, stamp included). DL-0 commits no report; these helpers serve
// CI artefact directories and local output directories.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { canonicalBytes, sha256Hex } from "@sentropic/diagram-core";
import { renderReportMarkdown, REPORT_MD_STAMP } from "./markdown.js";
import type { BijectionReport } from "./schema.js";
import type { HarnessDiagnostic, Outcome } from "../harness/types.js";

/** Write the report pair into `outDir` (§2.3): `<id>.report.json` + `<id>.report.md`. */
export async function writeReport(
  report: BijectionReport,
  outDir: string,
): Promise<{ readonly jsonPath: string; readonly mdPath: string }> {
  const jsonPath = join(outDir, `${report.fixture.id}.report.json`);
  const jsonBytes = `${canonicalBytes(report)}\n`;
  writeFileSync(jsonPath, jsonBytes);
  const jsonSha256 = sha256Hex(jsonBytes);
  const mdPath = join(outDir, `${report.fixture.id}.report.md`);
  writeFileSync(mdPath, renderReportMarkdown(report, { jsonPath, jsonSha256 }));
  return { jsonPath, mdPath };
}

/**
 * Check every `*.report.md` of `dir` (§2.3): the sibling JSON must exist, the
 * stamp digest must equal the JSON sha256, and the body must equal a fresh
 * render. Fails with `report-md-orphan` / `report-md-hand-edited` diagnostics.
 */
export function checkGeneratedReports(dir: string): Outcome<{ readonly checked: number }> {
  const diagnostics: HarnessDiagnostic[] = [];
  let checked = 0;
  if (!existsSync(dir)) return { ok: true, value: { checked } };
  for (const name of readdirSync(dir).filter((n) => n.endsWith(".report.md")).sort()) {
    checked += 1;
    const mdPath = join(dir, name);
    const jsonPath = join(dir, name.replace(/\.report\.md$/, ".report.json"));
    if (!existsSync(jsonPath)) {
      diagnostics.push({ origin: "ds-harness", code: "report-md-orphan", path: mdPath, message: "sibling report JSON is missing" });
      continue;
    }
    const jsonBytes = readFileSync(jsonPath, "utf8");
    const jsonSha256 = sha256Hex(jsonBytes);
    const md = readFileSync(mdPath, "utf8");
    const stamp = `<!-- generated by @sentropic/diagram-bijection ${REPORT_MD_STAMP} from ${jsonPath} sha256 ${jsonSha256}; do not edit -->`;
    const firstLine = md.split("\n", 1)[0] ?? "";
    if (firstLine !== stamp) {
      diagnostics.push({ origin: "ds-harness", code: "report-md-hand-edited", path: mdPath, message: "stamp differs" });
      continue;
    }
    const report = JSON.parse(jsonBytes) as BijectionReport;
    const rendered = renderReportMarkdown(report, { jsonPath, jsonSha256 });
    if (md !== rendered) {
      diagnostics.push({ origin: "ds-harness", code: "report-md-hand-edited", path: mdPath, message: "body differs from renderReportMarkdown" });
    }
  }
  return diagnostics.length === 0 ? { ok: true, value: { checked } } : { ok: false, diagnostics };
}
