// Generated Markdown of a loss report (§2.3): deterministic, LF only, never
// hand-written. The first line is the stamp with the source JSON path and its
// sha256; `checkGeneratedReports` (write.ts) re-renders and compares.
import type { BijectionReport } from "./schema.js";

export const REPORT_MD_STAMP = "report-md/1";

function cell(text: string): string {
  return `\`${text.replace(/\|/g, "\\|")}\``;
}

function plain(text: string): string {
  return text.replace(/\|/g, "\\|");
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const lines = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`];
  for (const row of rows) lines.push(`| ${row.join(" | ")} |`);
  return lines;
}

/**
 * Render the Markdown of `report`. `source` carries the path of the sibling
 * `.report.json` and its sha256 — both go into the stamp (§2.3).
 */
export function renderReportMarkdown(
  report: BijectionReport,
  source: { readonly jsonPath: string; readonly jsonSha256: string },
): string {
  const { jsonPath, jsonSha256 } = source;
  const lines: string[] = [
    `<!-- generated by @sentropic/diagram-bijection ${REPORT_MD_STAMP} from ${jsonPath} sha256 ${jsonSha256}; do not edit -->`,
    "",
    "## Summary",
    "",
    ...table(
      ["field", "value"],
      [
        ["format", cell(report.format)],
        ["chain", report.chain.map((c) => cell(c)).join(" ")],
        ["fixture", `${cell(report.fixture.path)} sha256 ${report.fixture.sha256.slice(0, 12)}`],
        ["pins", Object.entries(report.pins).map(([k, v]) => `${k}=${plain(v)}`).join(" ")],
        ["perFoldState", String(report.perFoldState)],
        ["foldStates", String(report.foldStates)],
        ["X1", `${report.x1.pass}/${report.x1.fail}`],
        ["X2", `${report.x2.pass}/${report.x2.fail}`],
        [
          "editSubset",
          `allowedMapped ${report.editSubset.allowedMapped.done}/${report.editSubset.allowedMapped.of}, forbiddenRefused ${report.editSubset.forbiddenRefused.done}/${report.editSubset.forbiddenRefused.of}, codes ${report.editSubset.codes.map((c) => cell(c)).join(" ") || "none"}`,
        ],
        ["verdict", plain(report.verdict)],
      ],
    ),
    "",
    "## Steps",
    "",
    ...table(
      ["step", "status", "reason", "pass", "fail", "codes"],
      (["S0", "S1", "S2", "S3", "S4", "S5", "S6"] as const).map((id) => {
        const s = report.steps[id];
        return [
          cell(id),
          plain(s.status),
          s.reason === undefined ? "" : plain(s.reason),
          s.pass === undefined ? "" : String(s.pass),
          s.fail === undefined ? "" : String(s.fail),
          (s.codes ?? []).map((c) => cell(c)).join(" "),
        ];
      }),
    ),
    "",
    "## Checks",
    "",
    ...table(
      ["id", "status", "reason"],
      report.checks.map((c) => [cell(c.id), plain(c.status), c.reason === undefined ? "" : plain(c.reason)]),
    ),
    "",
    "## Losses",
    "",
    ...table(
      ["what", "class", "code", "example", "count"],
      report.losses.map((l) => [
        plain(l.what),
        plain(l.class),
        l.code === undefined ? "" : cell(l.code),
        l.example === undefined ? "" : plain(l.example),
        l.count === undefined ? "" : String(l.count),
      ]),
    ),
    "",
    "## Not verified",
    "",
    ...(report.unverified.length === 0 ? ["- none"] : report.unverified.map((u) => `- ${plain(u)}`)),
    "",
  ];
  return lines.join("\n");
}
