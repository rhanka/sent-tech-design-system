/**
 * §2.9 witnesses of the loss report: W-DL0.4 (schema + semantic validation on
 * fixtures/report-vectors/) and W-DL0.6 (generated Markdown determinism and
 * the edit guard).
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync, cpSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { validateReport } from "../src/report/validate.js";
import { renderReportMarkdown } from "../src/report/markdown.js";
import { writeReport, checkGeneratedReports } from "../src/report/write.js";
import type { BijectionReport } from "../src/report/schema.js";

const vectorsDir = fileURLToPath(new URL("../fixtures/report-vectors/", import.meta.url));
const load = (name: string): unknown => JSON.parse(readFileSync(join(vectorsDir, name), "utf8")) as unknown;

const tmpDirs: string[] = [];
afterEach(() => {
  while (tmpDirs.length > 0) rmSync(tmpDirs.pop() as string, { recursive: true, force: true });
});
function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "dl-report-test-"));
  tmpDirs.push(dir);
  return dir;
}

describe("W-DL0.4 report vectors", () => {
  it.each(["valid-per-fold-state.json", "valid-text.json", "semantic-refused-unexercised.json"])("accepts %s", (name) => {
    const result = validateReport(load(name));
    expect(result.ok, result.ok ? "" : result.diagnostics.map((d) => d.message).join("; ")).toBe(true);
  });

  it.each([
    "invalid-unknown-key.json",
    "invalid-missing-s6.json",
    "invalid-missing-perfoldstate.json",
    "invalid-refused-no-code.json",
    "invalid-verdict-enum.json",
    "invalid-notrun-no-reason.json",
    "invalid-sha256-63.json",
    "semantic-x1-tally.json",
    "semantic-editsubset-code.json",
  ])("rejects %s", (name) => {
    const result = validateReport(load(name));
    expect(result.ok, `${name} must be rejected`).toBe(false);
  });

  it("the valid per-fold-state vector is a real runHarness report of tiny (25->5 states, demonstrated)", () => {
    const report = load("valid-per-fold-state.json") as BijectionReport;
    expect(report.schema).toBe("ds.diagram-bijection-report/1");
    expect(report.fixture.id).toBe("tiny");
    expect(report.foldStates).toBe(5);
    expect(report.verdict).toBe("demonstrated");
  });
});

describe("W-DL0.6 generated Markdown", () => {
  const report = load("valid-per-fold-state.json") as BijectionReport;

  it("renderReportMarkdown twice gives the same bytes, LF only, stamp first", () => {
    const a = renderReportMarkdown(report, "/tmp/x/tiny.report.json", "a".repeat(64));
    const b = renderReportMarkdown(report, "/tmp/x/tiny.report.json", "a".repeat(64));
    expect(a).toBe(b);
    expect(a).not.toContain("\r");
    expect(a.split("\n", 1)[0]).toBe(
      "<!-- generated by @sentropic/diagram-bijection report-md/1 from /tmp/x/tiny.report.json sha256 " + "a".repeat(64) + "; do not edit -->",
    );
  });

  it("checkGeneratedReports passes on a fresh writeReport pair", () => {
    const dir = tempDir();
    writeReport(dir, report);
    expect(checkGeneratedReports(dir)).toEqual({ ok: true });
  });

  it("checkGeneratedReports fails report-md-hand-edited on a hand-edited copy", () => {
    const dir = tempDir();
    const { mdPath } = writeReport(dir, report);
    const md = readFileSync(mdPath, "utf8");
    writeFileSync(mdPath, md.replace("## Summary", "## Summary (edited)"));
    const result = checkGeneratedReports(dir);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.failures[0]?.code).toBe("report-md-hand-edited");
  });

  it("checkGeneratedReports fails report-md-orphan when the sibling JSON is missing", () => {
    const dir = tempDir();
    const { jsonPath } = writeReport(dir, report);
    rmSync(jsonPath);
    const result = checkGeneratedReports(dir);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.failures[0]?.code).toBe("report-md-orphan");
  });

  it("a stamp digest mismatch is a hand edit", () => {
    const dir = tempDir();
    const { mdPath } = writeReport(dir, report);
    const md = readFileSync(mdPath, "utf8");
    writeFileSync(mdPath, md.replace(/sha256 [0-9a-f]{64}/, `sha256 ${"b".repeat(64)}`));
    const result = checkGeneratedReports(dir);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.failures[0]?.code).toBe("report-md-hand-edited");
  });
});
